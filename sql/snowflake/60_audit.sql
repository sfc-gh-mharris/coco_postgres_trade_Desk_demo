-- Stage 7a: durable audit archive in {{DB}}.AUDIT.
-- The mirror's tables reflect current Postgres state and its change feed keeps a rolling window,
-- and a demo reset (DROP SCHEMA desk) clears the mirror. The archive is the permanent record:
-- append-only copies keyed on (RUN_EPOCH, EVENT_ID), where RUN_EPOCH identifies the schema
-- instance so event ids that restart after a reset do not collide.

USE WAREHOUSE {{WH}};

CREATE TABLE IF NOT EXISTS {{DB}}.AUDIT.DESK_EVENTS_ARCHIVE (
  RUN_EPOCH STRING NOT NULL, EVENT_ID NUMBER NOT NULL, BREAK_ID STRING, ACTION_ID NUMBER, RUN_ID STRING,
  ACTOR_TYPE STRING, ACTOR_ID STRING, EVENT_TYPE STRING, AGENT_VERSION STRING, MODEL STRING,
  PAYLOAD VARIANT, OCCURRED_AT TIMESTAMP_LTZ, ARCHIVED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (RUN_EPOCH, EVENT_ID)
) COMMENT = 'Permanent append-only copy of desk.desk_events';

CREATE TABLE IF NOT EXISTS {{DB}}.AUDIT.ACTIONS_ARCHIVE (
  RUN_EPOCH STRING NOT NULL, ACTION_ID NUMBER NOT NULL, BREAK_ID STRING, ACTION_TYPE STRING, TIER NUMBER,
  RULE_ID STRING, STATUS STRING, QC_STATUS STRING, PROPOSED_BY_VERSION STRING, PAYLOAD VARIANT,
  PAYLOAD_SHA256 STRING, RATIONALE STRING, APPROVED_BY STRING, APPROVED_AT TIMESTAMP_LTZ, EXECUTED_AT TIMESTAMP_LTZ,
  CREATED_AT TIMESTAMP_LTZ, SNAPSHOT_AT TIMESTAMP_LTZ,
  PRIMARY KEY (RUN_EPOCH, ACTION_ID)
) COMMENT = 'Latest state of each proposed action, per schema instance';

CREATE TABLE IF NOT EXISTS {{DB}}.AUDIT.QC_REVIEWS_ARCHIVE (
  RUN_EPOCH STRING NOT NULL, REVIEW_ID NUMBER NOT NULL, ACTION_ID NUMBER, REVIEWER_VERSION STRING, MODEL STRING,
  REVIEW_KIND STRING, VERDICT STRING, REASON STRING, CREATED_AT TIMESTAMP_LTZ,
  PRIMARY KEY (RUN_EPOCH, REVIEW_ID)
);

CREATE TABLE IF NOT EXISTS {{DB}}.AUDIT.AGENT_RUNS_ARCHIVE (
  RUN_EPOCH STRING NOT NULL, RUN_ID STRING NOT NULL, BREAK_ID STRING, WORKER_ID STRING, AGENT_VERSION STRING,
  AGENT_ROLE STRING, MODEL STRING, STARTED_AT TIMESTAMP_LTZ, ENDED_AT TIMESTAMP_LTZ, OUTCOME STRING, TURNS NUMBER,
  INPUT_TOKENS NUMBER, OUTPUT_TOKENS NUMBER, LLM_MS NUMBER, TOOL_MS NUMBER,
  PRIMARY KEY (RUN_EPOCH, RUN_ID)
);

CREATE OR REPLACE PROCEDURE {{DB}}.AUDIT.ARCHIVE_DESK()
RETURNS STRING
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  epoch STRING;
  n_events INTEGER DEFAULT 0;
BEGIN
  -- The earliest event time of the current schema instance identifies it.
  SELECT TO_VARCHAR(MIN(OCCURRED_AT), 'YYYYMMDD"T"HH24MISS') INTO :epoch
    FROM {{MIRROR_DB}}.DESK.DESK_EVENTS;
  IF (:epoch IS NULL) THEN
    RETURN 'no events';
  END IF;

  INSERT INTO {{DB}}.AUDIT.DESK_EVENTS_ARCHIVE
    (RUN_EPOCH, EVENT_ID, BREAK_ID, ACTION_ID, RUN_ID, ACTOR_TYPE, ACTOR_ID, EVENT_TYPE, AGENT_VERSION, MODEL,
     PAYLOAD, OCCURRED_AT)
  SELECT :epoch, e.EVENT_ID, e.BREAK_ID, e.ACTION_ID, e.RUN_ID, e.ACTOR_TYPE, e.ACTOR_ID,
         e.EVENT_TYPE, e.AGENT_VERSION, e.MODEL, TRY_PARSE_JSON(e.PAYLOAD), e.OCCURRED_AT
    FROM {{MIRROR_DB}}.DESK.DESK_EVENTS e
   WHERE NOT EXISTS (SELECT 1 FROM {{DB}}.AUDIT.DESK_EVENTS_ARCHIVE a
                      WHERE a.RUN_EPOCH = :epoch AND a.EVENT_ID = e.EVENT_ID);
  n_events := SQLROWCOUNT;

  MERGE INTO {{DB}}.AUDIT.ACTIONS_ARCHIVE t
  USING (SELECT :epoch AS RUN_EPOCH, p.* FROM {{MIRROR_DB}}.DESK.PROPOSED_ACTIONS p) s
     ON t.RUN_EPOCH = s.RUN_EPOCH AND t.ACTION_ID = s.ACTION_ID
  WHEN MATCHED THEN UPDATE SET STATUS = s.STATUS, QC_STATUS = s.QC_STATUS, APPROVED_BY = s.APPROVED_BY,
       APPROVED_AT = s.APPROVED_AT, EXECUTED_AT = s.EXECUTED_AT, SNAPSHOT_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT (RUN_EPOCH, ACTION_ID, BREAK_ID, ACTION_TYPE, TIER, RULE_ID, STATUS, QC_STATUS,
       PROPOSED_BY_VERSION, PAYLOAD, PAYLOAD_SHA256, RATIONALE, APPROVED_BY, APPROVED_AT, EXECUTED_AT, CREATED_AT,
       SNAPSHOT_AT)
  VALUES (s.RUN_EPOCH, s.ACTION_ID, s.BREAK_ID, s.ACTION_TYPE, s.TIER, s.RULE_ID, s.STATUS,
          s.QC_STATUS, s.PROPOSED_BY_VERSION, TRY_PARSE_JSON(s.PAYLOAD), s.PAYLOAD_SHA256, s.RATIONALE,
          s.APPROVED_BY, s.APPROVED_AT, s.EXECUTED_AT, s.CREATED_AT, CURRENT_TIMESTAMP());

  INSERT INTO {{DB}}.AUDIT.QC_REVIEWS_ARCHIVE
  SELECT :epoch, r.REVIEW_ID, r.ACTION_ID, r.REVIEWER_VERSION, r.MODEL, r.REVIEW_KIND, r.VERDICT,
         r.REASON, r.CREATED_AT
    FROM {{MIRROR_DB}}.DESK.QC_REVIEWS r
   WHERE NOT EXISTS (SELECT 1 FROM {{DB}}.AUDIT.QC_REVIEWS_ARCHIVE a
                      WHERE a.RUN_EPOCH = :epoch AND a.REVIEW_ID = r.REVIEW_ID);

  INSERT INTO {{DB}}.AUDIT.AGENT_RUNS_ARCHIVE
  SELECT :epoch, r.RUN_ID, r.BREAK_ID, r.WORKER_ID, r.AGENT_VERSION, r.AGENT_ROLE, r.MODEL,
         r.STARTED_AT, r.ENDED_AT, r.OUTCOME, r.TURNS, r.INPUT_TOKENS, r.OUTPUT_TOKENS, r.LLM_MS,
         r.TOOL_MS
    FROM {{MIRROR_DB}}.DESK.AGENT_RUNS r
   WHERE NOT EXISTS (SELECT 1 FROM {{DB}}.AUDIT.AGENT_RUNS_ARCHIVE a
                      WHERE a.RUN_EPOCH = :epoch AND a.RUN_ID = r.RUN_ID);

  RETURN 'epoch ' || :epoch || ': archived ' || :n_events || ' new events';
END;
$$;

CREATE OR REPLACE TASK {{DB}}.AUDIT.ARCHIVE_DESK_TASK
  WAREHOUSE = {{WH}}
  SCHEDULE = '5 MINUTE'
  COMMENT = 'Copies new mirrored desk events, actions, reviews, and runs into the permanent archive'
AS CALL {{DB}}.AUDIT.ARCHIVE_DESK();

ALTER TASK {{DB}}.AUDIT.ARCHIVE_DESK_TASK RESUME;
