-- Stage: foundation. Run as ACCOUNTADMIN.
-- Database, schemas, warehouse, image repository, SQL stage, compute pool, and the four roles.
-- Every role is granted to ACCOUNTADMIN so the installer can act as each owner.

CREATE DATABASE IF NOT EXISTS {{DB}} COMMENT = 'Governed T+1 trade-break agent desk demo';
CREATE SCHEMA IF NOT EXISTS {{DB}}.REF;
CREATE SCHEMA IF NOT EXISTS {{DB}}.APP;
CREATE SCHEMA IF NOT EXISTS {{DB}}.AUDIT;

CREATE WAREHOUSE IF NOT EXISTS {{WH}}
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Break desk: reference lookups, mirror analytics, archive task';

CREATE IMAGE REPOSITORY IF NOT EXISTS {{DB}}.APP.DESK_REPO;
CREATE STAGE IF NOT EXISTS {{DB}}.APP.DESK_SQL
  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE') COMMENT = 'Postgres DDL and tests run by the installer';

CREATE COMPUTE POOL IF NOT EXISTS {{POOL}}
  MIN_NODES = 1 MAX_NODES = {{POOL_MAX_NODES}} INSTANCE_FAMILY = {{POOL_INSTANCE_FAMILY}}
  AUTO_RESUME = TRUE AUTO_SUSPEND_SECS = 600 INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Break desk agents, executor, approval apps';

-- Owns the executor, simulator, Streamlit console and installer jobs (ACCOUNTADMIN cannot own services).
CREATE ROLE IF NOT EXISTS {{SERVICE_ROLE}} COMMENT = 'Break desk: owns executor, console, simulator, jobs';
-- Owns the investigator and QC services. Read-only in Snowflake; never sees ground truth.
CREATE ROLE IF NOT EXISTS {{AGENT_ROLE}} COMMENT = 'Break desk: owns investigator and QC agents; read-only';
-- Owns the Node command center. Reads the full mirror (including ground truth) for the dashboard.
CREATE ROLE IF NOT EXISTS {{COMMAND_ROLE}} COMMENT = 'Break desk: owns the Node command center';
-- Humans: reach the approval apps and the flight recorder.
CREATE ROLE IF NOT EXISTS {{APPROVER_ROLE}} COMMENT = 'Break desk: approves tier-1/2 actions, operates the kill switch';

GRANT ROLE {{SERVICE_ROLE}} TO ROLE ACCOUNTADMIN;
GRANT ROLE {{AGENT_ROLE}} TO ROLE ACCOUNTADMIN;
GRANT ROLE {{COMMAND_ROLE}} TO ROLE ACCOUNTADMIN;
GRANT ROLE {{APPROVER_ROLE}} TO ROLE ACCOUNTADMIN;

GRANT USAGE ON DATABASE {{DB}} TO ROLE {{SERVICE_ROLE}};
GRANT USAGE ON DATABASE {{DB}} TO ROLE {{AGENT_ROLE}};
GRANT USAGE ON DATABASE {{DB}} TO ROLE {{COMMAND_ROLE}};
GRANT USAGE ON DATABASE {{DB}} TO ROLE {{APPROVER_ROLE}};
GRANT USAGE, CREATE SERVICE ON SCHEMA {{DB}}.APP TO ROLE {{SERVICE_ROLE}};
GRANT USAGE, CREATE SERVICE ON SCHEMA {{DB}}.APP TO ROLE {{AGENT_ROLE}};
GRANT USAGE, CREATE SERVICE ON SCHEMA {{DB}}.APP TO ROLE {{COMMAND_ROLE}};
GRANT USAGE ON SCHEMA {{DB}}.APP TO ROLE {{APPROVER_ROLE}};
GRANT USAGE ON SCHEMA {{DB}}.REF TO ROLE {{SERVICE_ROLE}};
GRANT USAGE ON SCHEMA {{DB}}.REF TO ROLE {{AGENT_ROLE}};
GRANT USAGE ON SCHEMA {{DB}}.REF TO ROLE {{COMMAND_ROLE}};
GRANT USAGE ON SCHEMA {{DB}}.AUDIT TO ROLE {{SERVICE_ROLE}};

GRANT USAGE ON WAREHOUSE {{WH}} TO ROLE {{SERVICE_ROLE}};
GRANT USAGE ON WAREHOUSE {{WH}} TO ROLE {{AGENT_ROLE}};
GRANT USAGE ON WAREHOUSE {{WH}} TO ROLE {{COMMAND_ROLE}};
GRANT USAGE ON WAREHOUSE {{WH}} TO ROLE {{APPROVER_ROLE}};

GRANT READ ON IMAGE REPOSITORY {{DB}}.APP.DESK_REPO TO ROLE {{SERVICE_ROLE}};
GRANT READ ON IMAGE REPOSITORY {{DB}}.APP.DESK_REPO TO ROLE {{AGENT_ROLE}};
GRANT READ ON IMAGE REPOSITORY {{DB}}.APP.DESK_REPO TO ROLE {{COMMAND_ROLE}};
GRANT READ ON STAGE {{DB}}.APP.DESK_SQL TO ROLE {{SERVICE_ROLE}};

GRANT USAGE, MONITOR ON COMPUTE POOL {{POOL}} TO ROLE {{SERVICE_ROLE}};
GRANT USAGE, MONITOR ON COMPUTE POOL {{POOL}} TO ROLE {{AGENT_ROLE}};
GRANT USAGE, MONITOR ON COMPUTE POOL {{POOL}} TO ROLE {{COMMAND_ROLE}};

GRANT BIND SERVICE ENDPOINT ON ACCOUNT TO ROLE {{SERVICE_ROLE}};
GRANT BIND SERVICE ENDPOINT ON ACCOUNT TO ROLE {{COMMAND_ROLE}};

GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE {{SERVICE_ROLE}};
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE {{AGENT_ROLE}};
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE {{APPROVER_ROLE}};

GRANT ROLE {{APPROVER_ROLE}} TO USER "{{INSTALL_USER}}";
