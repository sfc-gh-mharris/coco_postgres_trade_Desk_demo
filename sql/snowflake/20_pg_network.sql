-- Stage: Postgres network. Run as ACCOUNTADMIN after the instance is READY.
-- Egress: SPCS services may reach only this Postgres host on 5432.
-- Ingress: Postgres admits only Snowflake's published egress ranges (SPCS), refreshed at install.

CREATE OR REPLACE NETWORK RULE {{DB}}.APP.PG_EGRESS
  MODE = EGRESS TYPE = HOST_PORT VALUE_LIST = ('{{PG_HOST}}:5432')
  COMMENT = 'Break desk services to the desk Postgres instance';

CREATE EXTERNAL ACCESS INTEGRATION IF NOT EXISTS {{EAI}}
  ALLOWED_NETWORK_RULES = ({{DB}}.APP.PG_EGRESS) ENABLED = TRUE
  COMMENT = 'Break desk services to the desk Postgres instance';
ALTER EXTERNAL ACCESS INTEGRATION {{EAI}} SET ALLOWED_NETWORK_RULES = ({{DB}}.APP.PG_EGRESS);
GRANT USAGE ON INTEGRATION {{EAI}} TO ROLE {{SERVICE_ROLE}};
GRANT USAGE ON INTEGRATION {{EAI}} TO ROLE {{AGENT_ROLE}};
GRANT USAGE ON INTEGRATION {{EAI}} TO ROLE {{COMMAND_ROLE}};

CREATE OR REPLACE NETWORK RULE {{DB}}.APP.PG_INGRESS
  MODE = POSTGRES_INGRESS TYPE = IPV4 VALUE_LIST = ({{EGRESS_CIDRS}})
  COMMENT = 'SYSTEM$GET_SNOWFLAKE_EGRESS_IP_RANGES at install; earliest expiry {{EGRESS_EXPIRES}}';

CREATE NETWORK POLICY IF NOT EXISTS {{PG_POLICY}} ALLOWED_NETWORK_RULE_LIST = ({{DB}}.APP.PG_INGRESS)
  COMMENT = 'Break desk Postgres: Snowflake SPCS egress only';
ALTER NETWORK POLICY {{PG_POLICY}} SET ALLOWED_NETWORK_RULE_LIST = ({{DB}}.APP.PG_INGRESS);

ALTER POSTGRES INSTANCE "{{PG_INSTANCE}}" SET NETWORK_POLICY = '{{PG_POLICY}}';
